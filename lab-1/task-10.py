# 10.	Даны координаты трех вершин треугольника: (x1, y1), (x2, y2), (x3, y3). Найти его периметр и площадь 

import math

x1 = float(input("Введите координату x1: "))
y1 = float(input("Введите координату y1: "))
x2 = float(input("Введите координату x2: "))
y2 = float(input("Введите координату y2: "))
x3 = float(input("Введите координату x3: "))
y3 = float(input("Введите координату y3: "))

# Находим стороны треугольника
a = math.sqrt((x2 - x1)**2 + (y2 - y1)**2)
b = math.sqrt((x3 - x2)**2 + (y3 - y2)**2)
c = math.sqrt((x1 - x3)**2 + (y1 - y3)**2)

p = a + b + c
# Площадь по формуле Герона
s = math.sqrt((p/2) * (p/2 - a) * (p/2 - b) * (p/2 - c))

print(f"Периметр треугольника: {p}")
print(f"Площадь треугольника: {s}")