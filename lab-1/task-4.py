# 4.	Даны два ненулевых числа. Найти сумму, разность, произведение и частное их квадратов.

a = float(input("Введите ненулевое число a: "))
b = float(input("Введите ненулевое число b: "))

if a == 0 or b == 0:
    print("Ошибка: числа должны быть ненулевыми")
else:
    a_sq = a ** 2
    b_sq = b ** 2

    summ = a_sq + b_sq
    diff = a_sq - b_sq
    prod = a_sq * b_sq
    quot = a_sq / b_sq

    print(f"Сумма квадратов: {summ}")
    print(f"Разность квадратов: {diff}")
    print(f"Произведение квадратов: {prod}")
    print(f"Частное квадратов: {quot}")