# 3. Даны целые числа N (> 2), A и B. Сформировать и вывести целочисленный массив размера N,
# первый элемент которого равен A, второй равен B, а каждый последующий элемент равен сумме всех предыдущих

n = int(input("Введите размер массива N (> 2): "))
a = int(input("Введите A: "))
b = int(input("Введите B: "))

arr = [a, b] 

for i in range(2, n): 
    next_elem = sum(arr) 
    arr.append(next_elem)

print("Массив:", arr)