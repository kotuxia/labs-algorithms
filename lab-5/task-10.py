# 10. Дан целочисленный массив размера N, содержащий ровно два одинаковых элемента.
# Найти номера одинаковых элементов и вывести эти номера в порядке возрастания

arr = [4, 2, 7, 8, 2, 9] 

found = False
for i in range(len(arr)):
    for j in range(i + 1, len(arr)):
        if arr[i] == arr[j]:
            print(f"Одинаковые элементы находятся по номеру: {i+1} и {j+1}")
            found = True
            break
    if found:
        break