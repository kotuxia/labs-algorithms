# 9. Дан массив размера N. Найти номер его последнего локального максимума 
# (локальный максимум — это элемент, который больше любого из своих соседей).

arr = [1, 3, 2, 5, 1, 4, 2] # Пример

last_max_index = -1

for i in range(len(arr) - 2, 0, -1):
    if arr[i] > arr[i-1] and arr[i] > arr[i+1]:
        last_max_index = i
        break 

print(f"Номер последнего локального максимума (индекс): {last_max_index}")