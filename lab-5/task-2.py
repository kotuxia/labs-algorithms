# 2. Дано целое число N (> 1), а также первый член A и знаменатель D геометрической 
# прогрессии. Сформировать и вывести массив размера N, содержащий N первых членов данной прогрессии: A, A·D, A·D2 , A·D3 , . . .

n = int(input("Введите размер массива N: "))
a = int(input("Введите первый член A: "))
d = int(input("Введите знаменатель D: "))

arr = []
current = a

for i in range(n):
    arr.append(current)
    current = current * d  

print("Массив:", arr)