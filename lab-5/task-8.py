# 8. Дан массив A размера N. Найти минимальный элемент из его элементов с четными номерами: A2, A4, A6,

arr = [100, 5, 200, 3, 300, 7] # Пример


min_val = arr[1]

for i in range(1, len(arr), 2):
    if arr[i] < min_val:
        min_val = arr[i]

print(f"Минимальный элемент с четными номерами: {min_val}")