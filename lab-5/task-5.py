# 5. Дан массив A размера N. Вывести вначале его элементы с нечетными
# номерами в порядке возрастания номеров, а затем — элементы с четными номерами в порядке убывания номеров

arr = [10, 20, 30, 40, 50, 60, 70] 

print("Нечетные номера (возрастание):")
for i in range(0, len(arr), 2): 
    print(arr[i], end=" ")
print()

print("Четные номера (убывание):")

start_index = len(arr) - 2 if len(arr) % 2 == 0 else len(arr) - 1
for i in range(start_index, 0, -2):
    print(arr[i], end=" ")
print()