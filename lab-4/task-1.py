# 1. Факториал числа: Напишите функцию, которая рекурсивно вычисляет факториал заданного числа n.

def factorial(n):
    if n <= 1:  
        return 1
    else:     
        return n * factorial(n - 1)

n = int(input("Введите число для факториала: "))
if n >= 0:
    print(f"Факториал {n} = {factorial(n)}")
else:
    print("Ошибка: факториал есть только у неотрицательных чисел")