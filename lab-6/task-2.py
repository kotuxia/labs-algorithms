# 2. Дана матрица размера M × N и целое число K (1 ≤ K ≤ M).
# Найти сумму и произведение элементов K-й строки данной матрицы.

matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]
k = int(input("Введите номер строки K (от 1 до 3): "))

row = matrix[k - 1]

sum_row = sum(row)
prod_row = 1
for el in row:
    prod_row *= el

print(f"Сумма элементов {k}-й строки: {sum_row}")
print(f"Произведение элементов {k}-й строки: {prod_row}")