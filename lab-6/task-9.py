# 9. Дана матрица размера M × N. Упорядочить ее строки так, чтобы их первые элементы
# образовывали возрастающую последовательность.


matrix = [
    [5, 2, 3],
    [1, 9, 8],
    [7, 4, 6]
]

# Сортируем список строк matrix
matrix.sort(key=lambda row: row[0])

print("Матрица после сортировки строк:")
for row in matrix:
    print(row)