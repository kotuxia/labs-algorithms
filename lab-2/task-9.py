# 9. Дано целое число в диапазоне 100–999. Вывести строку-описание данного числа, 
# например: 256 — «двести пятьдесят шесть», 814 — «восемьсот четырнадцать».

n = int(input("Введите целое число от 100 до 999: "))

hundreds = ["", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот"]
tens = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто"]
teens = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
ones = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]

if 100 <= n <= 999:
    # Разбиваем число на цифры
    h = n // 100
    t = (n // 10) % 10    
    o = n % 10            

    result = hundreds[h]

    if t == 0:
        if o != 0:
            result += " " + ones[o]
    elif t == 1:
        result += " " + teens[o]
    else:
        result += " " + tens[t]
        if o != 0:
            result += " " + ones[o]

    print(result)
else:
    print("Число вне диапазона 100-999")