# 4. Даны координаты точки, не лежащей на координатных осях OX и OY.
# Определить номер координатной четверти, в которой находится данная точка

x = float(input("Введите координату x: "))
y = float(input("Введите координату y: "))

if x == 0 or y == 0:
    print("Точка лежит на координатной оси")
else:
    if x > 0 and y > 0:
        print("Точка находится в I четверти.")
    elif x < 0 and y > 0:
        print("Точка находится во II четверти.")
    elif x < 0 and y < 0:
        print("Точка находится в III четверти.")
    elif x > 0 and y < 0:
        print("Точка находится в IV четверти.")