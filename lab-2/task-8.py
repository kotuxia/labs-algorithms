# 8. Дано целое число в диапазоне 10–40, определяющее количество учебных заданий 
# по некоторой теме. Вывести строку-описание указанного количества заданий, обеспечив 
# правильное согласование числа со словами «учебное задание», например: 18 — «восемнадцать учебных заданий».

a = int(input("Введите количество заданий (число от 10 до 40): "))

num_words = [
    "десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
    "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать",
    "двадцать", "двадцать один", "двадцать два", "двадцать три", "двадцать четыре",
    "двадцать пять", "двадцать шесть", "двадцать семь", "двадцать восемь", "двадцать девять",
    "тридцать", "тридцать один", "тридцать два", "тридцать три", "тридцать четыре",
    "тридцать пять", "тридцать шесть", "тридцать семь", "тридцать восемь", "тридцать девять",
    "сорок"
]

if a >= 10 and a <= 40:
    i = a - 10
    num_text = num_words[i]

    # Проверяем последнюю цифру и число
    if a % 10 == 1 and a != 11:
        ending = "учебное задание"
    elif a % 10 in (2, 3, 4) and a not in (12, 13, 14):
        ending = "учебных задания"
    else:
        ending = "учебных заданий"

    print(f"{num_text} {ending}")
else: 
    print("Число вне данного диапазона")