# 6. Дано целое число, лежащее в диапазоне 1–999. Вывести его строку описание вида
# «четное двузначное число», «нечетное трехзначное число» и т. д.

a = int(input("Введите целое число от 1 до 999: "))

if a < 1 or a > 999:
    print("Число должно быть в диапазоне от 1 до 999")
else:
    if a % 2 == 0:
        parity = "четное"
    else:
        parity = "нечетное"

    if a < 10:
        print(f"{parity} однозначное число")
    elif a < 100:
        print(f"{parity} двузначное число")
    else:
        print(f"{parity} трехзначное число")