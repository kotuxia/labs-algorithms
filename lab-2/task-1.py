# 1. Даны две переменные целого типа: A и B. Если их значения не равны, то присвоить каждой переменной большее 
# из этих значений, а если равны, то присвоить переменным нулевые значения. Вывести новые значения переменных A и B.

a = int(input("Введите целое число a: "))
b = int(input("Введите целое число b: "))

if a != b:
    if a > b:
        b = a
    else:
        a = b
else:
    a = 0
    b = 0

print(f"Новые значения: a = {a}, b = {b}")