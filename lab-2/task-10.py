# 10. В восточном календаре принят 60-летний цикл, состоящий из 12- летних подциклов, обозначаемых названиями цвета: зеленый, 
# красный, желтый, белый и черный. В каждом подцикле годы носят названия животных: крысы, коровы, тигра, зайца, дракона, 
# змеи, лошади, овцы, обезьяны, курицы, собаки и свиньи. По номеру года определить его название, если 1984 год — 
# начало цикла: «год зеленой крысы».

year = int(input("Введите год: "))

animals = ["крысы", "коровы", "тигра", "зайца", "дракона", "змеи", "лошади", "овцы", "обезьяны", "курицы", "собаки", "свиньи"]
colors = ["зеленой", "красной", "желтой", "белой", "черной"]

if year >= 1984:
    diff = year - 1984
    
    animal_index = diff % 12
    color_index = (diff // 12) % 5
    
    print(f"{year} год — год {colors[color_index]} {animals[animal_index]}")
else:
    print("год должен быть 1984 или больше (по условию задачи).")