# 9. Начальный вклад в банке равен 1000 руб. Через каждый месяц размер вклада увеличивается на P процентов от
# имеющейся суммы (P — вещественное число, 0 < P < 25). По данному P определить, через сколько месяцев 
# размер вклада превысит 1100 руб., и вывести найденное количество месяцев K (целое число) и итоговый
# размер вклада S (вещественное число).

p = float(input("Введите процент P (0 < P < 25): "))

if p > 0 and p < 25:
    s = 1000.0
    k = 0     
    
    while s <= 1100:
        s = s * (1 + p / 100) 
        k = k + 1              
        
    print(f"Количество месяцев: {k}")
    print(f"Итоговый размер вклада: {s:.2f} руб.")
else:
    print("P должно быть в диапазоне от 0 до 25!")