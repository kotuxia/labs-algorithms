# 3. Дано целое число N (> 0). Найти квадрат данного числа, используя для его вычисления следующую 
# формулу: N2 = 1 + 3 + 5 + . . . + (2·N − 1). После добавления к сумме каждого слагаемого выводить
# текущее значение суммы

n = int(input("Введите целое число N (> 0): "))

if n > 0:
    total_sum = 0
    i = 1
    
    while i <= n:
        term = 2 * i - 1
        total_sum = total_sum + term
        print(f"Шаг {i}: добавили {term}, текущая сумма = {total_sum}")
        i += 1
        
    print(f"\nИтоговый квадрат числа {n} равен: {total_sum}")
else:
    print("N должно быть больше 0")