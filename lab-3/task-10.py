# 10. Даны целые положительные числа A и B. Найти их наибольший общий делитель (НОД), используя алгоритм Евклида
# НОД двух чисел не меняется, если большее число заменить на остаток от деления большего на меньшее.

a = int(input("Введите первое положительное число A: "))
b = int(input("Введите второе положительное число B: "))

if a > 0 and b > 0:
    orig_a = a
    orig_b = b
    
    # Алгоритм Евклида
    while b != 0:
        remainder = a % b  
        a = b              
        b = remainder
        
    print(f"НОД чисел {orig_a} и {orig_b} равен: {a}")
else:
    print("Числа должны быть положительными")