# 7. Даны положительные числа A и B (A > B). На отрезке длины A размещено максимально возможное
# количество отрезков длины B (без наложений). Не используя операции умножения и деления, 
# найти длину незанятой части отрезка A.

a = float(input("Введите длину отрезка A (A > B): "))
b = float(input("Введите длину отрезка B: "))

if a <= 0 or b <= 0 or a <= b:
    print("Не выполняются условия A > B > 0.")
else:
    while a >= b:
        a = a - b 
    print(f"Длина незанятой части отрезка: {a}")