# 6. Даны целые положительные числа A и B (A < B). Вывести все целые числа от A до B включительно; 
# при этом каждое число должно выводиться столько раз, каково его значение (например, число 3 выводится 3 раза)

a = int(input("Введите целое положительное число A (A < B): "))
b = int(input("Введите целое положительное число B (A < B): "))

if a >= b or a <= 0 or b <= 0:
    print("Не выполняются условия A < B и числа положительные.")
else:
    for i in range(a, b + 1):
        for j in range(i):
            print(i, end=" ")  
        print()